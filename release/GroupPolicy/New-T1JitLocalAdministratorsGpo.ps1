.SYNOPSIS
    Creates an example Group Policy that grants each T1JIT server group local administrator rights.
.DESCRIPTION
    Loads the active JIT configuration through Get-JITConfig and creates a complete computer GPO
    in every configured domain. Each GPO contains a Group Policy Preference for the built-in local
    Administrators group (well-known SID S-1-5-32-544). The preference adds the server-specific AD
    group generated by T1JIT without deleting existing local group members.

    In multi-domain mode, the generated member name is:
    <GroupDomainNetBIOS>\<AdminPrefix>%AD-DNSDomainName%<DomainSeparator>%ComputerName%

    In single-domain mode, the generated member name is:
    <GroupDomainNetBIOS>\<AdminPrefix>%ComputerName%

    GroupDomainNetBIOS is resolved from AdminGroupOU in the JIT configuration. This ensures
    that every GPO references the domain in which the central T1JIT groups are created, while
    AD-DNSDomainName still identifies the domain of the managed server in multi-domain mode.

    For each domain, the script creates the GPO AD object and SYSVOL structure, writes Groups.xml,
    registers the Local Users and Groups client-side extension, increments the GPO computer
    version, and links the policy to matching T1Searchbase OUs.
.PARAMETER ConfigurationFile
    Optional JIT configuration file path or Active Directory configuration common name. When
    omitted, Get-JITConfig uses JustInTimeConfig or its default AD configuration.
.PARAMETER Domain
    Optional DNS name of one configured domain for which the GPO is created. When omitted in
    multi-domain mode, the script processes every domain in the configured forest.
.PARAMETER GpoNamePrefix
    Prefix used for each domain-specific GPO name. The domain DNS name is appended.
.PARAMETER AdminPrefix
    Optional override for AdminPreFix from the JIT configuration.
.PARAMETER DomainSeparator
    Optional override for DomainSeparator from the JIT configuration.
.PARAMETER LinkDomainRoot
    Allows linking a GPO at a domain root when T1Searchbase contains <DomainRoot>. Without this
    explicit switch, the domain GPO is created but remains unlinked to avoid affecting every
    computer in that domain.
.PARAMETER Force
    Allows replacement of an existing Local Users and Groups preference in a GPO with the same
    name and suppresses the confirmation prompt. WhatIf still prevents all changes when both
    switches are supplied.
.PARAMETER Verbose
    Displays configuration loading, domain discovery, GPO creation, SYSVOL updates, and link details.
.PARAMETER WhatIf
    Shows which domain GPOs and links would be created or updated without changing Active Directory
    or SYSVOL.
.EXAMPLE
    .\New-T1JitLocalAdministratorsGpo.ps1 -WhatIf -Verbose
    Loads the active JIT configuration and displays a detailed preview of every domain-specific
    GPO and OU link without changing Active Directory or SYSVOL.
.EXAMPLE
    .\New-T1JitLocalAdministratorsGpo.ps1
    Creates one complete GPO per configured domain using AdminPreFix and DomainSeparator from
    the active JIT configuration.
.EXAMPLE
    .\New-T1JitLocalAdministratorsGpo.ps1 -Domain "child.contoso.com"
    Creates or updates the GPO only in the specified configured domain. Use this after a
    permission warning when different administrative credentials are required for that domain.
.EXAMPLE
    .\New-T1JitLocalAdministratorsGpo.ps1 `
        -ConfigurationFile "\\contoso.com\SYSVOL\contoso.com\Just-In-Time\JIT.config" `
        -AdminPrefix "T1Admin_" `
        -DomainSeparator "-" `
        -LinkDomainRoot
    Uses an explicit configuration, overrides two naming values, and permits domain-root links.
.INPUTS
    None. This script does not accept pipeline input.
.OUTPUTS
    PSCustomObject describing the GPO, target OUs, member-name expression, and Groups.xml path.
.NOTES
    Requires the GroupPolicy and ActiveDirectory Windows PowerShell modules and permissions to
    create GPOs, modify the GPO AD object, write to SYSVOL, and link GPOs to the target OUs.
    Script version 0.1.20260929.6
#>
